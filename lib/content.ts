export function makeQuestions(): Question[] {
  const out: Question[] = [];
  for (const [family, keys] of Object.entries(scales)) {
    keys.forEach((scale, k) => {
      const count =
        family === "riasec"
          ? 18
          : family === "klimov"
            ? k === 0
              ? 20
              : 19
            : 16;
      for (let n = 0; n < count; n++) {
        const action = activities[scale][n % 7];
        const context = [
          "Жеке тапсырмада",
          "Топтық жобада",
          "Жаңа тақырыпты үйренгенде",
        ][Math.floor(n / 7)];
        out.push({
          id: `q-${scale}-${n + 1}`,
          org: null,
          text:
            family === "skills"
              ? `${context} ${action} маған оңайырақ көрінеді.`
              : `${context} ${action} маған қызық.`,
          family: family as Question["family"],
          scale,
          reverse: false,
          active: true,
          version: 1,
        });
      }
    });
  }
  return out;
}

export function makeCareers(): Career[] {
  return rows.split("\n").map((row, n) => {
    const [name, description, r, k] = row.split("|");
    const targets: Record<string, number> = {};
    Object.values(scales)
      .flat()
      .forEach((s) => (targets[s] = 45));
    targets[r] = 90;
    targets[k] = 85;
    const skill =
      r === "a"
        ? "creative"
        : r === "s"
          ? "communication"
          : r === "c"
            ? "organization"
            : r === "e"
              ? "communication"
              : r === "r"
                ? "space"
                : "logic";
    targets[skill] = 85;
    return {
      id: `career-${n + 1}`,
      org: null,
      name,
      description,
      task: description,
      sector: labels[k],
      route:
        r === "r"
          ? "Колледж, тәжірибе және біліктілікті арттыру"
          : "Колледж немесе жоғары білім, тәжірибе",
      skills: [labels[skill], "Үздіксіз үйрену", "Жауапкершілік"],
      subjects:
        k === "art"
          ? ["Өнер", "Тіл және әдебиет"]
          : k === "nature"
            ? ["Биология", "География"]
            : k === "people"
              ? ["Тіл және әдебиет", "Қоғамтану"]
              : ["Математика", "Информатика"],
      targets,
      tags: [
        k === "nature" ? "outdoor" : "indoor",
        r === "s" || r === "e" ? "team" : "solo",
        r === "a" ? "creativity" : r === "s" ? "help" : "stability",
      ],
      active: true,
    };
  });
}
